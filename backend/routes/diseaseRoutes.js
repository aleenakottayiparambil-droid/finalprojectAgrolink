
const express = require("express");
const multer = require("multer");
const axios = require("axios");
const FormData = require("form-data");

const router = express.Router();

// Store uploaded images in memory with a 5 MB limit
const upload = multer({
    storage: multer.memoryStorage(),
    limits: {
        fileSize: 5 * 1024 * 1024
    },
    fileFilter: (req, file, callback) => {
        if (file.mimetype && file.mimetype.startsWith("image/")) {
            callback(null, true);
        } else {
            callback(new Error("Only image files are allowed"));
        }
    }
});

// Send the image to Flask and return prediction,
// Grad-CAM heatmap, and text-based XAI explanation.
router.post("/predict", upload.single("image"), async (req, res) => {
    try {
        if (!req.file) {
            return res.status(400).json({
                success: false,
                message: "Please upload a leaf image using the 'image' field."
            });
        }

        const form = new FormData();

        form.append("image", req.file.buffer, {
            filename: req.file.originalname || "leaf.jpg",
            contentType: req.file.mimetype
        });

        const response = await axios.post(
            "http://127.0.0.1:5001/predict",
            form,
            {
                headers: form.getHeaders(),
                maxBodyLength: 6 * 1024 * 1024,
                maxContentLength: 6 * 1024 * 1024,
                timeout: 120000
            }
        );

        const result = response.data;

        // Validate the prediction and Grad-CAM output
        if (
            result.status !== "success" ||
            typeof result.predicted_class !== "string" ||
            !result.predicted_class ||
            typeof result.confidence !== "number" ||
            !Number.isFinite(result.confidence) ||
            typeof result.gradcam_image !== "string" ||
            !result.gradcam_image.startsWith("data:image/png;base64,")
        ) {
            console.error("Incomplete Flask response:", {
                status: result.status,
                hasPrediction: Boolean(result.predicted_class),
                hasConfidence: typeof result.confidence === "number",
                hasGradcam: Boolean(result.gradcam_image),
                hasExplanation: typeof result.explanation === "string"
            });

            return res.status(502).json({
                success: false,
                message: "The disease service did not return a complete prediction and Grad-CAM image."
            });
        }

        // Return all results to the frontend
        return res.json({
            success: true,
            predicted_class: result.predicted_class,
            confidence: result.confidence,
            gradcam_image: result.gradcam_image,

            // Text explanation generated by Flask
            explanation:
                typeof result.explanation === "string"
                    ? result.explanation
                    : ""
        });

    } catch (error) {
        console.error(
            "Disease prediction error:",
            error.response?.data || error.message
        );

        return res.status(502).json({
            success: false,
            message:
                "Could not get a prediction and explanation from the disease detection service."
        });
    }
});

module.exports = router;
